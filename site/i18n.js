  const SUPPORTED = Object.keys(TRANSLATIONS);
  const STORAGE_KEY = "aq_lang";

  function detectLanguage() {
    const params = new URLSearchParams(window.location.search);
    const queryLang = params.get("lang");
    if (queryLang && SUPPORTED.includes(queryLang)) {
      return queryLang;
    }
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED.includes(saved)) {
      return saved;
    }
    const navLang = (navigator.language || "en").toLowerCase().split("-")[0];
    return SUPPORTED.includes(navLang) ? navLang : "en";
  }

  function applyLanguage(lang) {
    const code = SUPPORTED.includes(lang) ? lang : "en";
    const dict = TRANSLATIONS[code];
    document.documentElement.lang = code;
    document.title = dict.page_title;

    for (const el of document.querySelectorAll("[data-i18n]")) {
      const key = el.getAttribute("data-i18n");
      if (key && Object.hasOwn(dict, key)) {
        el.textContent = dict[key];
      }
    }

    const select = document.getElementById("lang-select");
    if (select) {
      select.value = code;
    }
    localStorage.setItem(STORAGE_KEY, code);
  }

  function initCopyButtons() {
    for (const btn of document.querySelectorAll(".copy-btn")) {
      btn.addEventListener("click", async () => {
        const targetId = btn.getAttribute("data-copy-target");
        const targetEl = targetId ? document.getElementById(targetId) : null;
        if (!targetEl) return;

        try {
          await navigator.clipboard.writeText(targetEl.textContent || "");
          const lang = document.documentElement.lang || "en";
          const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
          btn.textContent = dict.btn_copied;
          setTimeout(() => {
            const currentLang = document.documentElement.lang || "en";
            btn.textContent = (TRANSLATIONS[currentLang] || TRANSLATIONS.en).btn_copy;
          }, 1600);
        } catch {
          // Clipboard API unavailable in restricted contexts
        }
      });
    }
  }

  document.addEventListener("DOMContentLoaded", () => {
    const initialLang = detectLanguage();
    applyLanguage(initialLang);

    const select = document.getElementById("lang-select");
    if (select) {
      select.addEventListener("change", (event) => {
        applyLanguage(event.target.value);
      });
    }

    initCopyButtons();
  });
